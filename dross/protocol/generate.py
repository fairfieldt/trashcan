#!/usr/bin/env python3
"""Generate registry constants only. Wire codecs encode fields explicitly."""
from pathlib import Path
import argparse
base=Path(__file__).resolve().parent
rust=['// Generated by protocol/generate.py from schema.def; do not edit.\n']
chead=['/* Generated by protocol/generate.py from schema.def; do not edit. */\n#ifndef OSCAR_PROTOCOL_SCHEMA_H\n#define OSCAR_PROTOCOL_SCHEMA_H\n#include <stdint.h>\n']
seen=set()
for line in (base/'schema.def').read_text().splitlines():
    words=line.split()
    if not words or words[0].startswith('#'):continue
    kind,*args=words
    if kind=='PROTOCOL':
        name,value,major=args
        entries=[('PROTOCOL_'+name,value,'u32'),('MAJOR_'+name,major,'u16')]
    elif kind=='ORDINAL': entries=[('_'.join(args[:2]),args[2],'u32')]
    elif kind=='STATUS': entries=[('STATUS_'+args[0],args[1],'i32')]
    elif kind=='KIND': entries=[('KIND_'+args[0],args[1],'u16')]
    elif kind=='LIMIT': entries=[('MAX_'+args[0],args[1],'usize')]
    else:raise SystemExit('unknown schema record: '+line)
    for name,value,ty in entries:
        assert name not in seen,name
        seen.add(name)
        rust.append(f'pub const {name}: {ty} = {value};\n')
        chead.append(f'#define OSCAR_{name} ({value})\n')
chead.append('#endif\n')
outputs={base.parent/'user/rt/src/protocol/schema.rs':''.join(rust),base/'include/oscar_schema.h':''.join(chead)}
check=argparse.ArgumentParser();check.add_argument('--check',action='store_true');args=check.parse_args()
for path,data in outputs.items():
    if args.check:
        if not path.exists() or path.read_text()!=data:raise SystemExit(f'stale generated schema: {path}')
    else:path.write_text(data)
